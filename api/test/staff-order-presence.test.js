'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {Script}=require('node:vm');
const makePresence=require('../staff-order-presence');
const makeFlow=require('../system-flow');
const staff={role:'waiter',userId:'user-1'},manager={role:'manager',userId:'user-2'};
const a='11111111-1111-4111-8111-111111111111',b='22222222-2222-4222-8222-222222222222';
const table='33333333-3333-4333-8333-333333333333';
const lookup=async id=>id===table?{id,name:'Bàn 05',active:true}:null;
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');

test('employee choosing a table appears as selecting before a sale; only counts are visible',async()=>{
 let clock=10000;
 const presence=makePresence({now:()=>clock,ttlMs:45000});
 await presence.heartbeat({sessionId:a,tableId:table,stage:'selecting',cartItems:3},staff,lookup);
 await presence.heartbeat({sessionId:b,tableId:table,stage:'viewing'},manager,lookup);
 let snap=presence.snapshot();
 assert.deepEqual([snap.activeSessions,snap.selectingSessions,snap.cartItems,snap.activeTables],[2,1,3,1]);
 assert.deepEqual(snap.tables.map(x=>[x.tableName,x.selectingSessions,x.cartItems]),[['Bàn 05',1,3]]);
 assert(!JSON.stringify(snap).includes(a));
 assert(!JSON.stringify(snap).includes('user-1'));
 assert(!JSON.stringify(snap).includes(table));
 await presence.heartbeat({sessionId:a,tableId:table,stage:'submitting',cartItems:3},staff,lookup);
 snap=presence.snapshot();
 assert.equal(snap.selectingSessions,0);assert.equal(snap.submittingSessions,1);
 await presence.heartbeat({sessionId:a,tableId:table,stage:'ordered',cartItems:0},staff,lookup);
 assert.equal(presence.snapshot().orderedSessions,1);
 assert.equal(presence.snapshot().cartItems,0);
 presence.leave({sessionId:a},staff);assert.equal(presence.snapshot().activeSessions,1);
 clock+=46000;assert.equal(presence.snapshot().activeSessions,0);
});
test('permissions, ownership, invalid tables and bounded memory cannot be bypassed',async()=>{
 const p=makePresence({maxSessions:1});
 await assert.rejects(()=>p.heartbeat({sessionId:a,tableId:table}, {role:'bar',userId:'user-3'},lookup),{status:403});
 await assert.rejects(()=>p.heartbeat({sessionId:a,tableId:table},{role:'waiter',userId:'user-3',workArea:'equipment'},lookup),{status:403});
 await assert.rejects(()=>p.heartbeat({sessionId:a,tableId:'bad'},staff,lookup),{status:400});
 await assert.rejects(()=>p.heartbeat({sessionId:a,tableId:'44444444-4444-4444-8444-444444444444'},staff,lookup),{status:404});
 await p.heartbeat({sessionId:a,tableId:table,stage:'selecting',cartItems:2},staff,lookup);
 await assert.rejects(()=>p.heartbeat({sessionId:a,tableId:table},manager,lookup),{status:403});
 p.leave({sessionId:a},manager);
 assert.equal(p.snapshot().activeSessions,1);
 await assert.rejects(()=>p.heartbeat({sessionId:b,tableId:table},manager,lookup),{status:503});
 assert.equal(p.snapshot().cartItems,2);
});
test('100 separate phone sessions can be tracked without writing orders to PostgreSQL',async()=>{
 const p=makePresence({maxSessions:150});
 let tableReads=0;
 const check=async id=>{tableReads++;return lookup(id)};
 await Promise.all(Array.from({length:100},(_,i)=>{
  const session='55555555-5555-4555-8555-'+String(i).padStart(12,'0');
  return p.heartbeat({sessionId:session,tableId:table,stage:'selecting',cartItems:1},{role:'waiter',userId:'user-'+i},check);
 }));
 const s=p.snapshot();
 assert.equal(s.activeSessions,100);
 assert.equal(s.selectingSessions,100);
 assert.equal(s.cartItems,100);
 assert.equal(s.activeTables,1);
 assert.equal(tableReads,100);
});
test('system snapshot includes employee presence, and telemetry is NOT a fake order trace',async()=>{
 const p=makePresence();
 await p.heartbeat({sessionId:a,tableId:table,stage:'selecting',cartItems:4},staff,lookup);
 const pool={query:async q=>({rows:q.text?.includes('AS "orders24h"')?[{orders24h:0}]:[]})};
 const sys=makeFlow({pool,staffOrderPresence:p});
 assert.equal(sys.classify('POST','/api/staff/order-presence'),null);
 assert.equal(sys.classify('POST','/api/staff/order-presence/leave'),null);
 assert.deepEqual(sys.classify('POST','/api/staff/orders'),{module:'stafforder',route:'/api/staff/orders',method:'POST'});
 const result=await sys.recent();
 assert.equal(result.staffOrderPresence.selectingSessions,1);
 assert.equal(result.events.length,0);
 assert.equal(result.requests.length,0);
});
